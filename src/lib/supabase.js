import { createClient } from '@supabase/supabase-js';

const rawSupabaseUrl = import.meta.env.VITE_SUPABASE_URL;
const supabaseAnonKey = import.meta.env.VITE_SUPABASE_ANON_KEY;

// Clean and normalize the Supabase URL (strip /rest/v1 or trailing slashes if passed)
const cleanSupabaseUrl = rawSupabaseUrl
  ? rawSupabaseUrl.trim().replace(/\/rest\/v1\/?$/, '').replace(/\/+$/, '')
  : '';

// Check if credentials are validly supplied
export const isSupabaseConfigured = () => {
  return Boolean(
    cleanSupabaseUrl &&
    supabaseAnonKey &&
    cleanSupabaseUrl.startsWith('http') &&
    !cleanSupabaseUrl.includes('placeholder')
  );
};

// Initialize the real Supabase client if configured, otherwise provide null/fallback
export const supabase = isSupabaseConfigured()
  ? createClient(cleanSupabaseUrl, supabaseAnonKey.trim(), {
      auth: {
        persistSession: true,
        autoRefreshToken: true,
        detectSessionInUrl: true,
      },
    })
  : null;

